CREATE TABLE IF NOT EXISTS users (
    id          VARCHAR(36)  NOT NULL PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    email       VARCHAR(255),
    is_active   BOOLEAN      DEFAULT TRUE,
    created_by  VARCHAR(255),
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    updated_by  VARCHAR(255)
);

-- Database-generated key + full capability mixins (audit, soft delete, version).
-- Exercises insertAndReturnKey, batch, paging, soft delete and optimistic locking.
CREATE TABLE IF NOT EXISTS products (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    created_ts  TIMESTAMP,
    created_by  VARCHAR(255),
    updated_ts  TIMESTAMP,
    updated_by  VARCHAR(255),
    active      BOOLEAN      DEFAULT TRUE,
    version     BIGINT       DEFAULT 0
);

-- Audited but NOT soft-deletable / versioned — the AuditedEntity shape
-- (a created-then-updated record such as a process log or registration).
CREATE TABLE IF NOT EXISTS notes (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body        VARCHAR(500) NOT NULL,
    created_ts  TIMESTAMP,
    created_by  VARCHAR(255),
    updated_ts  TIMESTAMP,
    updated_by  VARCHAR(255)
);